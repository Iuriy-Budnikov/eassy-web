	<h1>Privacy Policy</h1>

	<p class="dates">
		<strong>Effective date:</strong> <time datetime="2026-08-12">August 12, 2026</time><br />
		<strong>Last updated:</strong> <time datetime="2026-08-12">August 12, 2026</time>
	</p>

	<p>
		This Privacy Policy explains how <strong>eassy</strong> ("eassy," "we," "us," or "our") handles
		information when you use the eassy iPhone app, Apple Watch companion, Live Activities, Dynamic
		Island features, and related services.
	</p>

	<p>
		eassy is designed around an <strong>on-device-first privacy model</strong>. eassy does not
		currently require an account, and core workout history, profile, templates, trends, and
		recommendation data are stored locally on your iPhone rather than synced to an eassy cloud
		account.
	</p>

	<h2>1. Privacy at a Glance</h2>

	<ul>
		<li>
			<strong>No eassy account is required.</strong> Your profile and core training data are stored
			locally on your device.
		</li>
		<li>
			<strong>No eassy iCloud or CloudKit sync.</strong> eassy does not currently sync your workout
			database to iCloud, CloudKit, or an eassy cloud account.
		</li>
		<li>
			<strong>Apple Health access is optional and permission-based.</strong> You decide which
			supported Health data eassy may read or write.
		</li>
		<li><strong>Health and fitness data is used for fitness functionality, not advertising.</strong></li>
		<li>
			<strong>On-device AI stays on-device.</strong> Built-in Apple Intelligence features process
			training information locally on supported devices.
		</li>
		<li>
			<strong>External sharing happens at your direction.</strong> The iOS share sheet and Analyze
			with ChatGPT are initiated by you.
		</li>
		<li><strong>We do not sell personal information or health information.</strong></li>
	</ul>

	<h2>2. Information eassy Processes</h2>

	<h3>Workout and Fitness Information</h3>

	<p>eassy may process information you enter or generate while using the app, including:</p>

	<ul>
		<li>workout names, dates, duration, exercises, sets, repetitions, and weights;</li>
		<li>distance and duration values;</li>
		<li>rest periods and set duration;</li>
		<li>perceived exertion / session RPE;</li>
		<li>workout volume and personal records;</li>
		<li>workout templates and supersets;</li>
		<li>training history and trends;</li>
		<li>training goal and training level;</li>
		<li>unit, week-start, and workout preferences;</li>
		<li>
			derived metrics such as Training Readiness, recovery information, Training Load Ratio,
			heart-rate-zone summaries, Smart Progression recommendations, and Smart Template
			recommendations.
		</li>
	</ul>

	<p>This information is primarily stored locally on your iPhone.</p>

	<h3>Training Profile Information</h3>

	<p>
		If you enter it directly or permit eassy to read it from Apple Health, eassy may process:
	</p>

	<ul>
		<li>biological sex / sex at birth;</li>
		<li>date of birth;</li>
		<li>height;</li>
		<li>body weight.</li>
	</ul>

	<p>
		This information is used to personalize fitness calculations such as heart-rate zones,
		readiness, training metrics, and recommendations.
	</p>

	<h2>3. Apple Health</h2>

	<p>Connecting Apple Health is optional.</p>

	<p>
		If you grant permission, eassy may read supported health and fitness information required by
		features you use, including:
	</p>

	<ul>
		<li>completed workouts;</li>
		<li>heart-rate samples;</li>
		<li>workout pace data;</li>
		<li>sleep duration and sleep-related information;</li>
		<li>heart-rate variability (HRV / SDNN);</li>
		<li>resting heart rate;</li>
		<li>biological sex;</li>
		<li>date of birth;</li>
		<li>height;</li>
		<li>body weight.</li>
	</ul>

	<p>
		When permitted, eassy may also write supported information to Apple Health, including completed
		workouts and supported perceived-exertion values.
	</p>

	<p>
		Apple Health information is used to provide features such as workout history, workout-detail
		charts, heart-rate zones, Training Readiness, Training Load Ratio, recovery calculations,
		trends, and fitness recommendations.
	</p>

	<p>
		<strong
			>eassy does not use Apple Health / HealthKit information for advertising, targeted marketing,
			or third-party data mining.</strong
		>
	</p>

	<p>eassy does not store personal health information in iCloud or CloudKit.</p>

	<p>
		Apple Health permissions are controlled by iOS. You may grant or revoke supported permissions
		through the Health app and applicable iOS privacy settings.
	</p>

	<h2>4. Apple Watch</h2>

	<p>
		When you use the eassy Apple Watch companion, eassy may process workout information generated
		during your session, including:
	</p>

	<ul>
		<li>workout state and exercise progress;</li>
		<li>set start and completion events;</li>
		<li>set and rest duration;</li>
		<li>heart rate and energy information available through the Apple Watch workout session;</li>
		<li>weight, repetition, rest, and other set values;</li>
		<li>edits made during an active workout.</li>
	</ul>

	<p>
		Workout information is exchanged between your iPhone and Apple Watch so that the active session
		remains synchronized.
	</p>

	<p>
		If automatic motion-based set detection is available and enabled in the version of eassy you
		use, motion signals may be processed on the Apple Watch to determine when a workout set appears
		to start or finish. These signals and resulting events are used for workout functionality, not
		advertising.
	</p>

	<h2>5. Calendar Access</h2>

	<p>
		If calendar integration is available in the version of eassy you use and you grant permission,
		eassy may read calendar information to provide calendar-related training context.
	</p>

	<p>
		Calendar access is read-only. eassy does not use this permission to create or modify calendar
		events.
	</p>

	<p>You can revoke Calendar permission in iOS Settings.</p>

	<h2>6. Notifications, Live Activities, and Push-to-Start</h2>

	<p>If you grant notification permission, eassy may use notifications for:</p>

	<ul>
		<li>rest-timer alerts;</li>
		<li>workout-related alerts;</li>
		<li>Live Activity and Dynamic Island functionality;</li>
		<li>Push-to-Start functionality.</li>
	</ul>

	<p>
		For Push-to-Start, a technical push or Live Activity token may need to be registered with the
		notification system or service responsible for delivering the request to your device.
	</p>

	<p>
		Such identifiers are intended only to route the requested notification or Live Activity and not
		for advertising or behavioral tracking.
	</p>

	<h2>7. On-Device AI</h2>

	<p>
		On supported versions of iOS, eassy can use Apple's on-device Foundation Models / Apple
		Intelligence to generate coaching information based on your training.
	</p>

	<p>For these built-in AI features:</p>

	<ul>
		<li>generation occurs on your device;</li>
		<li>
			workout and health data is not sent to OpenAI or another third-party LLM provider for this
			generation;
		</li>
		<li>no external AI API key or account is required;</li>
		<li>when on-device AI is unavailable, eassy uses deterministic fallback content.</li>
	</ul>

	<h2>8. Analyze with ChatGPT</h2>

	<p>
		eassy includes an optional <strong>Analyze with ChatGPT</strong> action for completed workouts.
	</p>

	<p>
		When you select this feature, eassy prepares a workout summary that may contain information such
		as:
	</p>

	<ul>
		<li>workout title and date;</li>
		<li>workout duration;</li>
		<li>perceived exertion / RPE;</li>
		<li>training goal;</li>
		<li>exercises;</li>
		<li>target sets;</li>
		<li>completed weights and repetitions;</li>
		<li>previous comparable workout performance.</li>
	</ul>

	<p>
		eassy then opens <code>chatgpt.com</code> in your browser with the workout information prepared
		for a new ChatGPT conversation.
	</p>

	<p>
		This action is <strong>initiated by you</strong>. eassy does not use the OpenAI API and does not
		automatically send your workout information to OpenAI in the background.
	</p>

	<p>
		Once information is opened or submitted to ChatGPT, it is processed according to OpenAI's own
		terms and privacy practices.
	</p>

	<p>
		For unusually large workouts, eassy may copy the prepared workout text to your device clipboard
		instead. Information on your clipboard can be pasted into apps or services you choose.
	</p>

	<h2>9. Sharing</h2>

	<p>
		eassy lets you share workout summaries and workout templates through the standard iOS share
		sheet.
	</p>

	<p>Information is shared only when you initiate the action and select a destination.</p>

	<p>
		The app, person, or service you select may process the shared information according to its own
		privacy practices. eassy does not control information after you intentionally provide it to
		another service.
	</p>

	<h2>10. How We Use Information</h2>

	<p>Information processed by eassy may be used to:</p>

	<ul>
		<li>record and display workouts;</li>
		<li>maintain workout history and templates;</li>
		<li>calculate workout statistics and personal records;</li>
		<li>calculate Training Readiness and recovery information;</li>
		<li>calculate Training Load Ratio and related metrics;</li>
		<li>generate training trends;</li>
		<li>personalize heart-rate zones;</li>
		<li>provide Smart Progression;</li>
		<li>provide Smart Template recommendations;</li>
		<li>synchronize workouts between iPhone and Apple Watch;</li>
		<li>recover an interrupted active workout;</li>
		<li>display Live Activities and Dynamic Island information;</li>
		<li>import permitted information from Apple Health;</li>
		<li>write permitted workout data to Apple Health;</li>
		<li>provide notifications you enable;</li>
		<li>perform sharing actions you initiate;</li>
		<li>maintain app functionality, security, integrity, and reliability.</li>
	</ul>

	<p>We do not use HealthKit information for advertising or third-party marketing profiles.</p>

	<h2>11. On-Device Storage</h2>

	<p>
		The core eassy product stores your workout database and training profile locally on your device.
	</p>

	<p>eassy currently:</p>

	<ul>
		<li>does not require a user account;</li>
		<li>does not operate cloud synchronization for your workout database;</li>
		<li>does not sync that database to an eassy cloud account;</li>
		<li>does not sync that database through iCloud or CloudKit.</li>
	</ul>

	<p>
		Because information that remains only on your device is not transmitted to eassy servers, we
		generally cannot remotely access, export, restore, or delete that information for you.
	</p>

	<p>
		Limited technical information may leave the device where necessary for a platform feature you
		enable, such as push-notification routing or an external share initiated by you.
	</p>

	<h2>12. Data Sharing and Third Parties</h2>

	<p>We do not sell your personal information or health information.</p>

	<p>Information may be processed by another party in these circumstances:</p>

	<h3>Apple</h3>

	<p>
		eassy uses Apple platform services including HealthKit, Apple Watch connectivity, notifications,
		Live Activities, Dynamic Island, and on-device Apple Intelligence.
	</p>

	<h3>OpenAI / ChatGPT</h3>

	<p>
		When—and only when—you choose <strong>Analyze with ChatGPT</strong>, selected workout information
		may be opened in ChatGPT through your browser.
	</p>

	<h3>Apps You Choose Through Share</h3>

	<p>
		Information you share through the iOS share sheet is provided to the destination you select.
	</p>

	<h3>Push-to-Start Service Providers</h3>

	<p>
		If an eassy-controlled server or another provider is used to register Push-to-Start tokens, that
		service may process the minimum technical information required to deliver the feature.
	</p>

	<h3>Legal Requirements</h3>

	<p>
		For information we actually control outside your device, we may disclose information where
		reasonably required to comply with applicable law, respond to valid legal process, protect legal
		rights, or protect users and the public.
	</p>

	<p>
		This does not give us access to information that exists only within your device's local eassy
		storage.
	</p>

	<h2>13. Data Retention and Deletion</h2>

	<h3>Local Data</h3>

	<p>
		Workout history, templates, profile information, settings, and derived metrics are retained
		locally until they are changed or removed through available app or device functionality.
	</p>

	<p>
		An active-workout recovery snapshot is stored only for the short period needed to restore an
		interrupted workout. The current product discards recovery snapshots older than approximately 12
		hours.
	</p>

	<h3>Apple Health</h3>

	<p>Apple Health information stored by Apple Health remains controlled through Apple Health.</p>

	<p>
		Revoking eassy's Health permission stops future access to the affected HealthKit data type. It
		does not necessarily remove information already stored in Apple Health or local eassy records
		previously imported from Apple Health.
	</p>

	<h3>Information Shared With Third Parties</h3>

	<p>
		Information you intentionally send to ChatGPT or another service is subject to that service's
		retention and deletion policies.
	</p>

	<h2>14. Your Choices and Controls</h2>

	<p>You can control access to your information through eassy, iOS, and Apple Health.</p>

	<p>You can:</p>

	<ul>
		<li>manage Apple Health read/write permissions;</li>
		<li>revoke Calendar access;</li>
		<li>change notification permissions;</li>
		<li>manage Apple Watch pairing and app access;</li>
		<li>choose whether to use external sharing;</li>
		<li>choose whether to use Analyze with ChatGPT;</li>
		<li>edit or remove information through available app controls;</li>
		<li>remove applicable local app data using device-level controls.</li>
	</ul>

	<p>
		Declining an optional permission may prevent the corresponding feature from functioning, but
		does not grant eassy access to the protected information.
	</p>

	<h2>15. Your Privacy Rights</h2>

	<p>
		Depending on where you live and which privacy laws apply, you may have rights concerning
		personal information controlled by us. These may include rights to:
	</p>

	<ul>
		<li>obtain information about processing;</li>
		<li>request access;</li>
		<li>request correction;</li>
		<li>request deletion;</li>
		<li>request restriction of certain processing;</li>
		<li>request portability where applicable;</li>
		<li>object to certain processing;</li>
		<li>withdraw consent where processing is based on consent.</li>
	</ul>

	<p>
		For information stored exclusively on your device and never transmitted to us, we may not have a
		server-side copy that we can access or delete on your behalf. Such information can instead be
		controlled through eassy, iOS, or Apple Health.
	</p>

	<p>
		If applicable California privacy law applies to us, you may also have rights concerning access,
		correction, deletion, and certain sale or sharing of personal information.
	</p>

	<p>
		<strong
			>eassy does not sell personal information and does not share personal information for
			cross-context behavioral advertising.</strong
		>
	</p>

	<p>Privacy requests concerning information we actually control can be sent to:</p>

	<p><a href="mailto:info@eassy.app">info@eassy.app</a></p>

	<h2>16. Security</h2>

	<p>
		eassy is designed to minimize unnecessary transmission of health and fitness information and
		relies on Apple's platform security and permission mechanisms for protected device data.
	</p>

	<p>However, no storage or transmission system can be guaranteed to be completely secure.</p>

	<p>
		You should protect access to your iPhone, Apple Watch, Apple ID, and any third-party services
		with which you choose to share information.
	</p>

	<h2>17. Health and Fitness Information</h2>

	<p>Health and fitness information may be sensitive.</p>

	<p>
		eassy accesses supported health information only for user-facing health and fitness
		functionality such as:
	</p>

	<ul>
		<li>workout tracking;</li>
		<li>workout history;</li>
		<li>heart-rate analysis;</li>
		<li>Training Readiness;</li>
		<li>Training Load Ratio;</li>
		<li>recovery information;</li>
		<li>fitness trends;</li>
		<li>training recommendations.</li>
	</ul>

	<p>
		We do not use Apple Health / HealthKit data for advertising, targeted marketing, or third-party
		data mining.
	</p>

	<p>
		Training Readiness, Training Load Ratio, heart-rate-zone information, recovery indicators, and
		related features provide fitness guidance and are not intended to constitute medical diagnoses.
	</p>

	<h2>18. Children's Privacy</h2>

	<p>
		The current eassy product does not include a child account system and does not require users to
		create an account.
	</p>

	<h2>19. International Users</h2>

	<p>
		The primary eassy workout database is stored on-device and is not currently synchronized through
		an eassy cloud service.
	</p>

	<h2>20. Website Privacy</h2>

	<p>This policy is intended to serve as the website privacy policy for the eassy application.</p>

	<p>The current product specification does not identify website:</p>

	<ul>
		<li>accounts;</li>
		<li>advertising;</li>
		<li>analytics;</li>
		<li>cookies;</li>
		<li>tracking technologies;</li>
		<li>contact forms;</li>
		<li>payment processing.</li>
	</ul>

	<h2>21. Changes to This Policy</h2>

	<p>
		We may update this Privacy Policy when our product, integrations, legal requirements, or privacy
		practices change.
	</p>

	<p>
		When the policy changes, we will update the <strong>Last updated</strong> date above and provide
		any additional notice required by applicable law.
	</p>

